import { chromium } from "playwright-core";
const B = "http://localhost:3100", OUT = process.argv[2] ?? ".";
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM ?? "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
let ok = 0; const fails = [];
const check = (c, m) => (c ? ok++ : fails.push(m));
const errs = [];
for (const vp of [{ width: 390, height: 844 }, { width: 1280, height: 900 }]) {
  const tag = vp.width;
  const ctx = await browser.newContext({ viewport: vp, hasTouch: vp.width < 600 });
  const page = await ctx.newPage();
  page.on("pageerror", (e) => errs.push(`${tag} ${e.message}`));
  page.on("console", (m) => m.type() === "error" && errs.push(`${tag} ${m.text()}`));
  await page.goto(`${B}/konto/logowanie`);
  await page.fill('input[name="email"]', "drugi@example.com"); await page.fill('input[name="password"]', "nowe-haslo-123");
  await page.click("form button.btn"); await page.waitForURL((u) => !u.pathname.startsWith("/konto"));
  await page.goto(`${B}/nauka`);
  check(await page.locator('a[href="/nauka/olimpiada"]').count() > 0, `${tag} zakładka Olimpiada`);
  check(await page.locator('a[href="/nauka/literatura"]').count() > 0, `${tag} zakładka Literatura`);
  await page.goto(`${B}/nauka/olimpiada`);
  check(await page.locator('[data-testid="olymp-stage"]').count() === 3, `${tag} trzy etapy`);
  const vis = await page.evaluate(() => { const el = document.querySelector(".subtabs"), on = el?.querySelector('[aria-selected="true"]'); if (!el || !on) return false; const b = el.getBoundingClientRect(), r = on.getBoundingClientRect(); return r.left >= b.left - 1 && r.right <= b.right + 1; });
  check(vis, `${tag} aktywna podzakładka widoczna w pasku`);
  const txt = await page.locator("main").innerText();
  check(/50 pytań testowych jednokrotnego wyboru/.test(txt) && /60 minut/.test(txt), `${tag} etap I: 50 pytań, 60 min`);
  check(/135 pkt/.test(txt), `${tag} suma zawodów centralnych 135`);
  check(/Gospodarka wobec wyzwań demograficznych/.test(txt), `${tag} hasło XL`);
  check(await page.locator('[data-testid="olymp-themes"] tbody tr').count() === 40, `${tag} 40 haseł edycji`);
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${tag} olimpiada: brak poziomego przewijania`);
  await page.screenshot({ path: `${OUT}/olimpiada-${tag}.png` });
  await page.goto(`${B}/nauka/literatura`);
  check(await page.locator('[data-testid="lit-item"]').count() === 22, `${tag} 22 pozycje literatury (${await page.locator('[data-testid="lit-item"]').count()})`);
  check(await page.locator('[data-testid="lit-previous"] tbody tr').count() >= 10, `${tag} poprzednie edycje`);
  const ext = await page.locator('main a[target="_blank"]').evaluateAll((as) => as.every((a) => a.rel.includes("noopener")));
  check(ext, `${tag} linki zewnętrzne z noopener`);
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${tag} literatura: brak poziomego przewijania`);
  await page.screenshot({ path: `${OUT}/literatura-${tag}.png` });
  await ctx.close();
}
await browser.close();
console.log(`OK: ${ok} błędów: ${fails.length}`, JSON.stringify(fails, null, 1), JSON.stringify(errs.slice(0, 5)));
